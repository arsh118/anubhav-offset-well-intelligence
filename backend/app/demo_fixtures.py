def build_well_fixtures() -> List[Dict[str, Any]]:
    """Copy well fixtures and generate precise, deterministic offset coordinates."""
    result = []
    for fixture in WELL_FIXTURES:
        row = dict(fixture)
        if row.get("location") == "origin":
            row["coordinates"] = FIELD_ORIGINS[row["field"]]
        else:
            field, distance_km, bearing = row["offset"]
            row["coordinates"] = destination_point(*FIELD_ORIGINS[field], distance_km, bearing)
        result.append(row)
    return result


