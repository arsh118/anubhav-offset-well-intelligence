def destination_point(latitude: float, longitude: float, distance_km: float, bearing_deg: float) -> Tuple[float, float]:
    """Return a deterministic WGS84-like destination for the fixture map."""
    angular_distance = distance_km / EARTH_RADIUS_KM
    bearing = radians(bearing_deg)
    lat1 = radians(latitude)
    lon1 = radians(longitude)
    lat2 = asin(sin(lat1) * cos(angular_distance) + cos(lat1) * sin(angular_distance) * cos(bearing))
    lon2 = lon1 + atan2(
        sin(bearing) * sin(angular_distance) * cos(lat1),
        cos(angular_distance) - sin(lat1) * sin(lat2),
    )
    return round(degrees(lat2), 6), round(degrees(lon2), 6)


